export const translate = (
  locale: Locale,
  key: string,
  values: Readonly<Record<string, string | number>> = {},
): string => {
  const template = translations[locale][key] ?? key;
  return Object.entries(values).reduce(
    (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
    template,
  );
};
